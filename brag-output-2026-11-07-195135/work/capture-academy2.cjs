const { open } = require('./lib-academy.cjs');
const fs = require('fs');
(async () => {
  const { b, p } = await open({ dpr: 3, mode: 'academy' });
  const bx = {};
  const get = async (k, loc) => { bx[k] = await loc.first().boundingBox().catch(() => null); };
  const toLabel = async (re) => { await p.evaluate((src) => { const r = new RegExp(src, 'i'); const h = [...document.querySelectorAll('*')].find((e) => r.test(e.textContent.trim()) && e.children.length === 0); h && h.scrollIntoView({ block: 'start' }); }, re); await p.waitForTimeout(700); };
  await p.waitForTimeout(500);
  await p.screenshot({ path: 'cap/ac-home.png' });
  await get('homeHero', p.locator('text=Bristol, England').locator('xpath=ancestor::*[contains(.,"Staff") or contains(.,"STAFF")][1]'));
  await get('playersRow', p.locator('text=1 asking to join'));
  await p.getByRole('button', { name: 'Players', exact: true }).last().click(); await p.waitForTimeout(1400);
  await p.screenshot({ path: 'cap/ac-players.png' });
  await toLabel('^EVERYONE');
  await p.screenshot({ path: 'cap/ac-everyone.png' });
  await get('alexRow', p.locator('text=Alex Carter').first().locator('xpath=ancestor::*[self::button or self::li or self::a][1]'));
  await p.getByRole('button', { name: 'Stats', exact: true }).last().click(); await p.waitForTimeout(2000);
  await toLabel('^LEADERBOARD$');
  await p.screenshot({ path: 'cap/ac-leaders.png' });
  await get('leo', p.locator('text=Leo Martins').first());
  await get('jayden', p.locator('text=Jayden Okafor').first());
  await toLabel('^TEAM PICKS');
  await p.locator('text=Saturday v Oakfield').first().click(); await p.waitForTimeout(1500);
  await p.screenshot({ path: 'cap/ac-pick-open.png' });
  await p.locator('button[aria-label="Close"]').last().click().catch(() => {}); await p.waitForTimeout(900);
  await p.getByRole('button', { name: 'Tables', exact: true }).last().click(); await p.waitForTimeout(1000);
  await p.locator('text=Northern Junior League').first().click(); await p.waitForTimeout(1400);
  await p.screenshot({ path: 'cap/ac-table.png' });
  await get('table', p.locator('table').first());
  fs.writeFileSync('cap/ac-boxes.json', JSON.stringify(bx, null, 1));
  console.log(JSON.stringify(bx));
  await b.close();
})();
