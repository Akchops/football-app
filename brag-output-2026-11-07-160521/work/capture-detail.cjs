const { open } = require('./lib.cjs');
const fs = require('fs');
(async () => {
  const { b, p } = await open(3);
  const shot = async (n) => { await p.waitForTimeout(900); await p.screenshot({ path: `cap/${n}.png` }); };
  const box = async (loc) => loc.boundingBox();
  const boxes = {};
  boxes.promptEnter = await box(p.getByRole('button', { name: 'Enter result' }));
  await p.getByRole('button', { name: 'Enter result' }).click();
  await p.waitForTimeout(800);
  await p.getByRole('button', { name: 'Increase Wanderers FC' }).click();
  await p.getByRole('button', { name: 'Increase Wanderers FC' }).click();
  for (let i = 0; i < 6; i++) await p.getByRole('button', { name: 'Increase Saves' }).click();
  await p.getByRole('button', { name: 'Save result' }).click();
  await p.waitForTimeout(1500);
  await p.screenshot({ path: 'cap/dbg.png' });
  console.log((await p.evaluate(() => [...document.querySelectorAll('button')].map(b => (b.getAttribute('aria-label')||b.innerText).trim().replace(/\n/g,' / ')).filter(Boolean).join(' | '))).slice(0, 1500));
  await p.locator('button[aria-label^="Fri 6 November"], button[aria-label*="6 November"]').first().click();
  await p.waitForTimeout(700);
  await shot('day6');
  const row = p.locator('text=Eastfield Town').first();
  await row.click();
  await shot('detail');
  boxes.performance = await box(p.locator('.performance'));
  boxes.summary = await box(p.locator('.perf-breakdown summary'));
  await p.locator('.perf-breakdown summary').click();
  await shot('detail-open');
  boxes.breakdown = await box(p.locator('.perf-breakdown'));
  boxes.breakdownText = await p.locator('.perf-breakdown').innerText();
  boxes.perfText = await p.locator('.performance').innerText();
  fs.writeFileSync('cap/detail-boxes.json', JSON.stringify(boxes, null, 1));
  console.log(JSON.stringify(boxes, null, 1));
  await b.close();
})();
